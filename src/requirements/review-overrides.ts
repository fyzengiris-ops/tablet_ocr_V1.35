export function getPersistedRequirementReviewOverride(requirementId: string) {
  return persistedRequirementReviewOverrides[requirementId];
}

export function applyPersistedRequirementReviewOverride(requirement: RequirementItem): RequirementItem {
  const override = getPersistedRequirementReviewOverride(requirement.id);

  if (!override?.sections || override.sections.length === 0) {
    return requirement;
  }

  const displaySection = override.sections.find((section) => section.id === 'display.description');
  const operationDescriptionSection = override.sections.find((section) => section.id === 'operation.description');
  const permissionSection = override.sections.find((section) => section.id === 'operation.permission');
  const dataFlowSection = override.sections.find((section) => section.id === 'operation.dataFlow');
  const exceptionsSection = override.sections.find((section) => section.id === 'operation.exceptions');

  return {
    ...requirement,
    display: {
      ...requirement.display,
      title: displaySection?.title ?? requirement.display.title,
      description: displaySection?.items ? [...displaySection.items] : requirement.display.description,
    },
    operation: {
      ...requirement.operation,
      title: operationDescriptionSection?.title ?? requirement.operation.title,
      description: operationDescriptionSection?.items
        ? [...operationDescriptionSection.items]
        : requirement.operation.description,
      permission: permissionSection?.items ? [...permissionSection.items] : requirement.operation.permission,
      dataFlow: dataFlowSection?.items ? [...dataFlowSection.items] : requirement.operation.dataFlow,
      exceptions: exceptionsSection?.items ? [...exceptionsSection.items] : requirement.operation.exceptions,
    },
  };
}

export function applyPersistedRequirementReviewOverrides(requirements: RequirementItem[]) {
  return requirements.map(applyPersistedRequirementReviewOverride);
}
